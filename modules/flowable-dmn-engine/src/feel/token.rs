#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Number(f64),
    String(String),
    Name(String),
    Null,
    True,
    False,
    If,
    Then,
    Else,
    For,
    Return,
    Some,
    Every,
    Satisfies,
    In,
    And,
    Or,
    Not,
    Plus,
    Minus,
    Star,
    Slash,
    Power,
    Equal,
    NotEqual,
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Colon,
    Dot,
    DotDot,
    Eof,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub start: usize,
    pub end: usize,
}
